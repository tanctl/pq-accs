#!/usr/bin/env python3
"""Generate tests/fixtures.cairo.

Independent references: hashlib SHAKE-256 and a from-spec Keccak-f[1600] for the hash; falcon.py's
`Falcon.verify` (standard compressed encoding) for every accept/reject expectation.

    gen_fixtures.py --falcon-py PATH --key KEY.json --out tests/fixtures.cairo
"""

from __future__ import annotations

import argparse
import hashlib
import os
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "signer"))
import falcon512_signer as fs  # noqa: E402

# ---- Keccak-f[1600] from FIPS 202 ------------------------------------------------------------
RC = [0x0000000000000001, 0x0000000000008082, 0x800000000000808A, 0x8000000080008000,
      0x000000000000808B, 0x0000000080000001, 0x8000000080008081, 0x8000000000008009,
      0x000000000000008A, 0x0000000000000088, 0x0000000080008009, 0x000000008000000A,
      0x000000008000808B, 0x800000000000008B, 0x8000000000008089, 0x8000000000008003,
      0x8000000000008002, 0x8000000000000080, 0x000000000000800A, 0x800000008000000A,
      0x8000000080008081, 0x8000000000008080, 0x0000000080000001, 0x8000000080008008]
ROT = [[0, 36, 3, 41, 18], [1, 44, 10, 45, 2], [62, 6, 43, 15, 61], [28, 55, 25, 21, 56],
       [27, 20, 39, 8, 14]]
M64 = (1 << 64) - 1


def rol(x, r):
    return ((x << r) | (x >> (64 - r))) & M64 if r else x


def keccak_f(a):
    a = a[:]
    for rc in RC:
        c = [a[x] ^ a[x + 5] ^ a[x + 10] ^ a[x + 15] ^ a[x + 20] for x in range(5)]
        d = [c[(x - 1) % 5] ^ rol(c[(x + 1) % 5], 1) for x in range(5)]
        a = [a[i] ^ d[i % 5] for i in range(25)]
        b = [0] * 25
        for x in range(5):
            for y in range(5):
                b[y + 5 * ((2 * x + 3 * y) % 5)] = rol(a[x + 5 * y], ROT[x][y])
        a = [b[i] ^ ((~b[(i % 5 + 1) % 5 + 5 * (i // 5)]) & b[(i % 5 + 2) % 5 + 5 * (i // 5)]) for i in range(25)]
        a[0] ^= rc
    return a


def check_keccak_against_hashlib():
    msg = bytes(range(72))
    block = bytearray(msg + b"\x1f" + bytes(136 - 73))
    block[135] |= 0x80
    st = [int.from_bytes(block[8 * i:8 * i + 8], "little") for i in range(17)] + [0] * 8
    st = keccak_f(st)
    out = b"".join(st[i].to_bytes(8, "little") for i in range(17))
    assert out == hashlib.shake_256(msg).digest(136), "reference Keccak-f mismatch"


# ---- Cairo emitters ----------------------------------------------------------------------------
def arr(name, xs, ty="felt252"):
    body = "".join(f"        {hex(x) if ty == 'felt252' else x},\n" for x in xs)
    return f"pub fn {name}() -> Array<{ty}> {{\n    array![\n{body}    ]\n}}\n"


def felt(name, x):
    return f"pub fn {name}() -> felt252 {{\n    {hex(x)}\n}}\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--falcon-py", type=Path, required=True)
    ap.add_argument("--key", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    random.seed(20261017)
    fpy, _div = fs.falcon_modules(args.falcon_py)
    from falcon import serialize_poly  # type: ignore
    from encoding import compress  # type: ignore
    scheme = fpy.Falcon(512)
    sk, h = fs.load_key(args.key)
    vk = serialize_poly(h)
    slen = scheme.param.sig_bytelen - 41

    def ref_verify(mh: int, salt: bytes, s2: list[int]) -> bool:
        enc = compress(s2, slen)
        if enc is False:
            return False
        return scheme.verify(vk, mh.to_bytes(32, "little"), bytes([0x39]) + salt + enc)

    check_keccak_against_hashlib()
    out = ["//! GENERATED by scripts/gen_fixtures.py. Do not edit.", ""]

    # Keccak-f KATs (inputs and outputs as 25 lanes).
    kat_in = [[0] * 25, list(range(1, 26)), [random.getrandbits(64) for _ in range(25)]]
    for i, s in enumerate(kat_in):
        out.append(arr(f"keccak_in_{i}", s, "u128"))
        out.append(arr(f"keccak_out_{i}", keccak_f(s), "u128"))

    # Hash-to-point vectors: one 8-permutation and one 9-permutation stream.
    for name, want in (("h2p_8", 8), ("h2p_9", 9)):
        while True:
            mh = random.getrandbits(250)
            salt = os.urandom(40)
            words, perms = fs.hash_to_point_words(mh, salt)
            if perms == want:
                break
        out.append(felt(f"{name}_msg", mh))
        out.append(felt(f"{name}_salt_a", int.from_bytes(salt[:20], "little")))
        out.append(felt(f"{name}_salt_b", int.from_bytes(salt[20:], "little")))
        out.append(arr(f"{name}_words", words, "u16"))
        out.append(arr(f"{name}_mid", fs.pack_mid_state(fs.sponge_state(mh, salt, 4))))

    # Verifier vectors.
    out.append(arr("public_key", fs.pack_public_key(h)))
    other_h = [random.randrange(fs.Q) for _ in range(512)]
    out.append(arr("other_public_key", fs.pack_public_key(other_h)))
    cases = []  # (msg, signature felts, expected)

    def add_valid(grind: bool, want_perms: int):
        while True:
            mh = random.getrandbits(250)
            salt, s2 = fs.sign_raw(fpy, sk, mh, grind=grind)
            if fs.hash_to_point_words(mh, salt)[1] == want_perms:
                break
        assert ref_verify(mh, salt, s2)
        cases.append((mh, fs.encode_signature(mh, salt, s2, h), True))
        return mh, salt, s2

    base = [add_valid(True, 8) for _ in range(4)] + [add_valid(False, 9) for _ in range(2)]
    mh, salt, s2 = base[0]
    # wrong message (S4 for the signed message, and S4 recomputed for the wrong one)
    assert not ref_verify(mh + 1, salt, s2)
    cases.append((mh + 1, fs.encode_signature(mh, salt, s2, h), False))
    cases.append((mh + 1, fs.encode_signature(mh + 1, salt, s2, h), False))
    # one s2 coefficient changed
    for pos in (0, 255, 511):
        t = s2[:]
        t[pos] += 1
        assert not ref_verify(mh, salt, t)
        cases.append((mh, fs.encode_signature(mh, salt, t, h), False))
    # salt changed
    t_salt = bytes([salt[0] ^ 1]) + salt[1:]
    assert not ref_verify(mh, t_salt, s2)
    cases.append((mh, fs.encode_signature(mh, t_salt, s2, h), False))
    # s2 = 0 and an over-norm s2
    zero = [0] * 512
    assert not ref_verify(mh, salt, zero)
    cases.append((mh, fs.encode_signature(mh, salt, zero, h), False))
    big = [260 if i % 2 == 0 else -260 for i in range(512)]
    assert sum(x * x for x in big) > fs.SIG_BOUND_512 and not ref_verify(mh, salt, big)
    cases.append((mh, fs.encode_signature(mh, salt, big, h), False))
    # format-level rejections (no falcon.py counterpart): carried NTT(H) altered, non-canonical
    # s2 top digit, oversized salt, S4 altered (a lane, the unused top of the last felt, a felt
    # >= 2^192), wrong length
    sig = fs.encode_signature(mh, salt, s2, h)
    t = sig[:]; t[34 + 7] = (t[34 + 7] + 1) % fs.STARK_P
    cases.append((mh, t, False))
    t = sig[:]; t[0] += fs.Q**8  # top digit of the first u128 half becomes >= q
    cases.append((mh, t, False))
    t = sig[:]; t[32] += 1 << 160
    cases.append((mh, t, False))
    for pos, delta in ((162, 1), (162 + 4, 1 << 128), (170, 1 << 64), (163, 1 << 192)):
        t = sig[:]; t[pos] += delta
        cases.append((mh, t, False))
    cases.append((mh, sig[:-1], False))

    for i, (m, s, e) in enumerate(cases):
        out.append(felt(f"case_{i}_msg", m))
        out.append(arr(f"case_{i}_sig", s))
    out.append(f"pub const N_CASES: u32 = {len(cases)};\n")
    out.append("pub fn case_expected() -> Array<bool> {\n    array![" + ", ".join("true" if e else "false" for _, _, e in cases) + "]\n}\n")
    # dispatcher for the case index
    out.append("pub fn case(i: u32) -> (felt252, Array<felt252>) {\n" + "".join(
        f"    if i == {i} {{\n        return (case_{i}_msg(), case_{i}_sig());\n    }}\n" for i in range(len(cases)))
        + "    panic!(\"no such case\")\n}\n")
    args.out.write_text("\n".join(out))
    print(f"wrote {args.out}: {len(cases)} verifier cases", file=sys.stderr)


if __name__ == "__main__":
    main()
