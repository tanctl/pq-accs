#!/usr/bin/env python3
"""Generate the key class for one Falcon-512 public key: a Scarb package with a contract whose
`ntt_h` returns NTT(H) / 128 (the scaled 128-point transform the account verifies with). Declare
the built class, then pass its hash to the account constructor next to the public key.

    gen_key_class.py --key KEY.json --out DIR [--name Falcon512Key]
    (cd DIR && scarb build)   # target/dev/<package>_<name>.contract_class.json
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "signer"))
import falcon512_signer as fs  # noqa: E402


def source(ntt_h: list[int], name: str) -> str:
    fields = "".join(f"        f{i}: felt252,\n" for i in range(len(ntt_h)))
    body = "".join(f"            f{i}: {hex(x)},\n" for i, x in enumerate(ntt_h))
    return f"""//! GENERATED by scripts/gen_key_class.py: the key class of one Falcon-512 public key.

#[starknet::contract]
pub mod {name} {{
    #[storage]
    struct Storage {{}}

    /// 128 felts, serialized as exactly those felts (no length prefix, no loop).
    #[derive(Drop, Serde)]
    struct NttH {{
{fields}    }}

    /// NTT(H) / 128 for this key.
    #[external(v0)]
    fn ntt_h(self: @ContractState) -> NttH {{
        NttH {{
{body}        }}
    }}
}}
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--key", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--name", default="Falcon512Key")
    args = ap.parse_args()
    h = [int(v) for v in json.loads(args.key.read_text())["h"]]
    (args.out / "src").mkdir(parents=True, exist_ok=True)
    (args.out / "Scarb.toml").write_text(
        '[package]\nname = "falcon512_key"\nversion = "0.1.0"\nedition = "2024_07"\n\n'
        '[dependencies]\nstarknet = "2.18.0"\n\n[[target.starknet-contract]]\ncasm = true\n')
    (args.out / "src" / "lib.cairo").write_text(source(fs.ntt_public_key(h), args.name))
    print(f"wrote {args.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
