#!/usr/bin/env python3
"""Generate src/keccak.cairo: two Keccak-f[1600] permutations evaluated together.

Each u128 lane holds lane k of permutation A in its low 64 bits and lane k of permutation B in its
high 64 bits. XOR/AND/OR act on both halves at once, every rotation amount is shared by the two
halves, and pi only reorders whole lanes, so one pass over packed lanes computes both permutations.

    gen_keccak.py --out src/keccak.cairo
"""

from __future__ import annotations

import argparse
from pathlib import Path

P = 2**251 + 17 * 2**192 + 1
RC = [0x0000000000000001, 0x0000000000008082, 0x800000000000808A, 0x8000000080008000,
      0x000000000000808B, 0x0000000080000001, 0x8000000080008081, 0x8000000000008009,
      0x000000000000008A, 0x0000000000000088, 0x0000000080008009, 0x000000008000000A,
      0x000000008000808B, 0x800000000000008B, 0x8000000000008089, 0x8000000000008003,
      0x8000000000008002, 0x8000000000000080, 0x000000000000800A, 0x800000008000000A,
      0x8000000080008081, 0x8000000000008080, 0x0000000080000001, 0x8000000080008008]
ROT = [[0, 36, 3, 41, 18], [1, 44, 10, 45, 2], [62, 6, 43, 15, 61], [28, 55, 25, 21, 56],
       [27, 20, 39, 8, 14]]
BOTH = 1 + (1 << 64)

HEADER = """// Portions derived from OpenZeppelin cairo-pq-verifiers (MIT License, Copyright (c) 2026 OpenZeppelin).
//! GENERATED by scripts/gen_keccak.py. Do not edit.
//!
//! Two Keccak-f[1600] permutations at once. Lane k of the input is `a_k + b_k * 2^64`, where a and
//! b are the states of two independent permutations; the output packs f(a) and f(b) the same way.
//! - XOR/AND/OR on a u128 act on both 64-bit halves, and pi only reorders whole lanes.
//! - A rotation by R rotates each half: with t = x & T_R (the top R bits of each half),
//!   rotl_R(x) = (x - t) * 2^R + t / 2^(64-R), evaluated in the field and range-checked to u128.
//! - chi_i = b_i ^ (~b_{i+1} & b_{i+2}) is computed as (b_i ^ b_{i+1}) ^ (b_{i+1} | b_{i+2}): one
//!   bitwise instance per adjacent pair yields both terms, so chi needs no complement.
//! - theta is fused into the rho+pi terms; iota XORs the round constant into both halves of lane 0.

/// The u128 bitwise libfunc: AND, XOR and OR of one operand pair from a single builtin instance
/// (corelib exposes it only through the separate `&`, `^`, `|` operators).
extern fn bitwise(lhs: u128, rhs: u128) -> (u128, u128, u128) implicits(core::integer::Bitwise) nopanic;
"""


def mask(r: int) -> int:
    return (((1 << r) - 1) << (64 - r)) * BOTH


def rot_fn(r: int) -> str:
    k2 = (pow(2, -(64 - r), P) - (1 << r)) % P
    return f"""
/// rotl by {r} of both 64-bit halves; `m` = the top {r} bits of each half.
#[inline(always)]
fn rot{r}(x: u128, m: u128) -> u128 {{
    let (t, _, _) = bitwise(x, m);
    let v: felt252 = x.into() * {hex(1 << r)} + t.into() * {hex(k2)};
    match v.try_into() {{
        Some(r) => r,
        None => core::panic_with_felt252(0),
    }}
}}
"""


def s(i: int) -> str:
    return f"s{i:02d}"


def round_code(rc: str, idx: int) -> str:
    o = [f"    // round {idx}"]
    for x in range(5):
        o.append(f"    let c{x} = " + " ^ ".join(s(x + 5 * y) for y in range(5)) + ";")
    for x in range(5):
        o.append(f"    let d{x} = c{(x - 1) % 5} ^ rot1(c{(x + 1) % 5}, m1);")
    b = {}
    for x in range(5):
        for y in range(5):
            dst = y + 5 * ((2 * x + 3 * y) % 5)
            r = ROT[x][y]
            term = f"{s(x + 5 * y)} ^ d{x}"
            b[dst] = f"rot{r}({term}, m{r})" if r else term
    for i in range(25):
        o.append(f"    let b{i:02d} = {b[i]};")
    for y in range(5):
        for x in range(5):
            o.append(f"    let (_, x{y}{x}, o{y}{x}) = bitwise(b{5 * y + x:02d}, b{5 * y + (x + 1) % 5:02d});")
    for y in range(5):
        for x in range(5):
            line = f"    let {s(5 * y + x)} = x{y}{x} ^ o{y}{(x + 1) % 5}"
            if y == 0 and x == 0:
                line += f" ^ {rc}"
            o.append(line + ";")
    return "\n".join(o)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    rots = sorted({1} | {r for row in ROT for r in row if r})
    out = [HEADER]
    out += [rot_fn(r) for r in rots]
    lanes = ", ".join(s(i) for i in range(25))
    out.append("\n/// Keccak-f[1600] of the two states packed in `state` (lane k = a_k + b_k * 2^64).")
    out.append("pub fn keccak_f1600_x2(state: [u128; 25]) -> [u128; 25] {")
    out.append("    // Rotation masks and round constants are passed in so that they sit in the callee's frame")
    out.append("    // (writing a frame cell into a builtin input is one instruction, an immediate takes two);")
    out.append("    // the 24 rounds run as two calls of one 12-round body.")
    masks = "[" + ", ".join(hex(mask(r)) for r in rots) + "]"
    out.append(f"    let masks = {masks};")
    for half in range(2):
        rcs = "[" + ", ".join(hex(RC[12 * half + i] * BOTH) for i in range(12)) + "]"
        out.append(f"    let state = rounds12(state, masks, {rcs});")
    out.append("    state")
    out.append("}\n")
    out.append(f"fn rounds12(state: [u128; 25], masks: [u128; {len(rots)}], rc: [u128; 12]) -> [u128; 25] {{")
    out.append(f"    let [{lanes}] = state;")
    out.append("    let [" + ", ".join(f"m{r}" for r in rots) + "] = masks;")
    out.append("    let [" + ", ".join(f"rc{i}" for i in range(12)) + "] = rc;")
    out += [round_code(f"rc{i}", i) for i in range(12)]
    out.append(f"    [{lanes}]")
    out.append("}\n")
    args.out.write_text("\n".join(out))


if __name__ == "__main__":
    main()
